package model.dungeon;
/**
 * Represents which dungeon a {@link Dungeon} is.
 */
public enum DungeonCode{
    /**
     * Yasudaya Ryokan, a Hot Springs dungeon.
     * Modifiers - Stronger Heat, Hot Waters
     * Dungeon Style - Pools
     * Unlocks Mikan Mochi
     */
    YASUDAYA_RYOKAN,
    /**
     * Izu-Mito Sea Paradise, an Aquarium dungeon.
     * Modifiers - Faster Bats, Stronger Heals
     * Dungeon Style - A lot of water blocking paths
     * Unlocks Air Shoes
     */
    IZU_MITO_SEA_PARADISE,
    /**
     * Numazu Deep Sea Aquarium, an Aquarium dungeon.
     * Modifiers - Crippled Bats, Rebreather, Stronger Skeletons, Faster Skeletons
     * Dungeon Style - Full Water
     * Unlocks Bat Tamer
     */
    NUMAZU_DEEP_SEA_AQUARIUM,
    /**
     * Shougetsu Confectionary, a Candy dungeon.
     * Modifiers - Stronger Heals, Gold Tax
     * Dungeon Style - A lot of Treasure
     * Unlocks the Shop
     */
    SHOUGETSU_CONFECTIONARY,
    /**
     * Nagahama Castle Ruins, a Ruins dungeon.
     * Modifiers - Stronger Bats, Stronger Skeletons, Faster Bats, Faster Skeletons
     * Dungeon Style - Broken Structures
     * Unlocks Chocolate Mint Icecream
     */
    NAGAHAMA_CASTLE_RUINS,
    /**
     * Numazugoyotei, a Forest dungeon.
     * Modifiers - Stronger Heals, Stronger Walls, Faster Bats
     * Dungeon Style - Foresty Walls
     * Unlocks Kurosawa Macha
     */
    NUMAZUGOYOTEI,
    /**
     * Uchiura Bay Pier, a Beach dungeon.
     * Modifiers - Stronger Walls, Rebreather, Faster Skeletons
     * Dungeon Style - Bodies of Water
     * Unlocks Shovel Upgrade
     */
    UCHIURA_BAY_PIER,
    /**
     * Awashima Marine Park, a Water Park dungeon.
     * Modifiers - Faster Skeletons, Stronger Heals
     * Dungeon Style - A Lotta Treasure locked behind Challenges
     * Unlocks Stewshine
     */
    AWASHIMA_MARINE_PARK,
    /**
     * The Siren's Lair.
     */
    SIRENS_LAIR
}