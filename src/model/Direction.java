package model;
/**
 * Which direction a Creature is Facing.
 */
public enum Direction {
    /**
     * Up, or negative Y.
     */
    UP,
    /**
     * Down, or positive Y.
     */
    DOWN,
    /**
     * Left, or negative X.
     */
    LEFT,
    /**
     * Right, or positive X.
     */
    RIGHT,
}
