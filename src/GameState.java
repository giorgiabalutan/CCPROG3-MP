/**
 * Indicates what state the game is currently in.
 */
public enum GameState{
    /**
     * The player is currently in the Main Menu.
     */
    MAIN_MENU,
    /**
     * The player is currently preparing in the Overworld.
     */
    OVERWORLD,
    /**
     * The player is currently challenging one of the Dungeons.
     */
    DUNGEON,
    /**
     * The player is currently Shopping.
     */
    SHOP
}